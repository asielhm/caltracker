import { readFile, mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
const root = resolve(import.meta.dirname, "..");
const files = {
  "i18n.js": "text/javascript",
  "brand.css": "text/css",
  "welcome.html": "text/html",
  "welcome.css": "text/css",
  "welcome.js": "text/javascript",
  "favicon.ico": "image/x-icon",
  "assets/brand/mark.svg": "image/svg+xml",
  "assets/brand/logo.svg": "image/svg+xml",
  "assets/brand/apple-touch-icon.png": "image/png",
  "assets/brand/nutriar-editorial.webp": "image/webp",

  "index.html": "text/html; charset=utf-8",
  "app.js": "text/javascript",
  "foods.js": "text/javascript",
  "video-foods.js": "text/javascript",
  "nutrition.js": "text/javascript",
  "ui.js": "text/javascript",
  "health-shortcut.js": "text/javascript",
  "diary-data.js": "text/javascript",
  "diary-sync.js": "text/javascript",
  "camera.js": "text/javascript",
  "style.css": "text/css",
  "assets/meal.jpg": "image/jpeg",
};
const assets = {};
for (const [file, type] of Object.entries(files))
  assets["/" + file] = {
    type,
    body: (await readFile(resolve(root, "dist", file))).toString("base64"),
  };
try {
  assets["/nutriar-source.zip"] = {
    type: "application/zip",
    body: (await readFile(resolve(root, "dist/nutriar-source.zip"))).toString(
      "base64",
    ),
  };
} catch {}
const api = await readFile(resolve(root, "api.mjs"), "utf8");
const worker = (
  await readFile(resolve(root, "worker/index.mjs"), "utf8")
).replace(/import\s*\{\s*createApi\s*\}\s*from\s*['"]\.\.\/api\.mjs['"];?/, "");
await mkdir(resolve(root, "dist/server"), { recursive: true });
await writeFile(
  resolve(root, "dist/server/index.js"),
  `// Generated by npm run build:worker.\nconst ASSETS=${JSON.stringify(assets)};\n${api}\n${worker}`,
);
console.log(
  "Built hosted Worker with",
  Object.keys(assets).length,
  "embedded assets.",
);
